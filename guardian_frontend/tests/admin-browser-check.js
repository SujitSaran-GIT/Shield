// Run in agent-browser eval --stdin after opening /tests/admin-browser.html.
(async () => {
  const results = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  const wait = async predicate => { for (let i = 0; i < 200; i++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error('UI wait timed out'); };
  const button = text => [...document.querySelectorAll('button')].find(node => node.textContent.trim() === text);
  const open = async () => { button('Open administrator').focus(); button('Open administrator').click(); await wait(() => document.querySelector('dialog[open]')); };
  const loaded = () => wait(() => !document.querySelector('[aria-busy="true"]'));
  const confirm = async () => { document.querySelector('input[type=checkbox]').click(); await wait(() => [...document.querySelectorAll('dialog button')].some(node => /^(Activate|Deactivate) administrator$/.test(node.textContent.trim()) && !node.disabled)); };
  const fixture = window.adminFixture;
  fixture.loadDelay = true;
  await open();
  check(button('Deactivate administrator').disabled, 'action disabled while loading');
  fixture.loadDelay = false; fixture.releaseLoad(); await loaded();
  check(document.querySelector('select').disabled, 'role editing disabled');
  check(document.body.textContent.includes('Role changes are unavailable'), 'disabled role explanation visible');
  check(button('Deactivate administrator').disabled, 'confirmation required');
  const dialog = document.querySelector('dialog');
  const rect = dialog.getBoundingClientRect();
  check(rect.left >= 0 && rect.right <= innerWidth && rect.height <= innerHeight, 'dialog fits viewport');
  check(!!document.getElementById(dialog.getAttribute('aria-labelledby')), 'dialog has accessible title');
  await confirm();
  fixture.delay = true;
  button('Deactivate administrator').click(); button('Deactivate administrator').click();
  await wait(() => fixture.calls === 1);
  check(button('Deactivate administrator').disabled, 'action disabled while pending');
  check(fixture.calls === 1, 'duplicate submission prevented');
  dialog.dispatchEvent(new Event('cancel', { cancelable: true }));
  check(dialog.open, 'pending operation prevents dialog dismissal');
  fixture.release();
  await wait(() => !document.querySelector('dialog'));
  check(window.adminStore.getState().users.users[0].status === 'SUSPENDED', 'deactivation refreshes directory state');
  check(document.activeElement === button('Open administrator'), 'focus restored to opener');
  fixture.delay = false;
  await open(); await loaded();
  check(!!button('Activate administrator'), 'suspended administrator offers activation');
  await confirm(); button('Activate administrator').click();
  await wait(() => !document.querySelector('dialog'));
  check(window.adminStore.getState().users.users[0].status === 'ACTIVE', 'activation refreshes directory state');
  fixture.fail = true;
  await open(); await loaded(); await confirm(); button('Deactivate administrator').click();
  await wait(() => document.querySelector('[role=alert]'));
  check(document.querySelector('[role=alert]').textContent.includes('permission'), 'forbidden operation displays error');
  check(!document.querySelector('[role=alert]').textContent.includes('private'), 'server details hidden');
  check(window.adminStore.getState().users.users[0].status === 'ACTIVE', 'failed operation preserves status');
  button('Cancel').click(); await wait(() => !document.querySelector('dialog'));
  fixture.fail = false; fixture.refreshFail = true; fixture.calls = 0;
  await open(); await loaded(); await confirm(); button('Deactivate administrator').click();
  await wait(() => document.querySelector('[role=alert]'));
  check(document.querySelector('[role=alert]').textContent.includes('status change was saved'), 'refresh failure distinguishes saved mutation');
  check(button('Deactivate administrator').disabled, 'saved mutation cannot be submitted again after refresh failure');
  button('Cancel').click();
  return { passed: results.length, viewport: [innerWidth, innerHeight], results };
})()
