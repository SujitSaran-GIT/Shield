// Run with agent-browser eval --stdin on /tests/audit-browser.html.
(async () => {
  const results = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const wait = async predicate => { for (let i = 0; i < 240; i++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error('Audit UI timed out'); };
  const button = label => [...document.querySelectorAll('button')].find(node => node.textContent.trim() === label && node.getClientRects().length > 0);
  const setInput = async (node, value) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(node, value); node.dispatchEvent(new Event('input', { bubbles: true })); await new Promise(resolve => setTimeout(resolve, 30)); };
  const fixture = window.auditFixture;
  await wait(() => button('View event') && !button('Refresh').disabled);
  check(document.documentElement.scrollWidth <= innerWidth, 'audit log table scrolls within viewport');
  check(fixture.calls.some(call => call.url === '/audits'), 'unfiltered list endpoint loaded');
  check(fixture.calls.some(call => call.url === '/audits/kpis'), 'KPI endpoint loaded');
  check(fixture.calls.some(call => call.url === '/audits/recent'), 'recent endpoint loaded');
  check(fixture.calls.every(call => call.headers.Authorization === 'Bearer browser-test-access' && call.withCredentials), 'requests carry signed-in bearer and cookie credentials');
  fixture.delayDetails = true;
  button('View event').focus(); button('View event').click();
  await wait(() => document.querySelector('dialog [role=status]'));
  check(button('Refresh event').disabled, 'detail loading prevents duplicate reads');
  check(button('Export event').disabled, 'unloaded event cannot be exported');
  fixture.delayDetails = false; fixture.release();
  await wait(() => document.querySelector('dialog')?.textContent.includes('Fresh event detail'));
  const dialog = document.querySelector('dialog');
  const rect = dialog.getBoundingClientRect();
  check(rect.left >= 0 && rect.right <= innerWidth && rect.height <= innerHeight, 'event dialog fits viewport');
  check(!!document.getElementById(dialog.getAttribute('aria-labelledby')), 'event dialog has accessible title');
  check(fixture.calls.some(call => call.url.endsWith('/01234567-89ab-cdef-0123-456789abcdef')), 'opening event fetches real detail endpoint');
  fixture.detailStatus = 403; button('Refresh event').click();
  await wait(() => document.querySelector('dialog [role=alert]'));
  check(document.querySelector('dialog [role=alert]').textContent.includes('permission'), 'detail forbidden error displayed');
  check(!document.querySelector('dialog').textContent.includes('Fresh event detail'), 'failed refresh clears previously fetched details');
  button('Close').click(); await wait(() => !document.querySelector('dialog'));
  check(document.activeElement === button('View event'), 'event dialog restores keyboard focus');
  button('Next').click();
  await wait(() => fixture.calls.some(call => call.url === '/audits' && call.params.page === 1));
  check(true, 'pagination requests selected page');
  button('Filters').click();
  await wait(() => document.querySelector('form[aria-label="Audit filters"]'));
  const [start, end] = document.querySelectorAll('input[type=datetime-local]');
  await setInput(start, '2026-10-22T10:00'); await setInput(end, '2026-10-01T10:00');
  button('Apply filters').click();
  await wait(() => document.querySelector('form [role=alert]'));
  check(!fixture.calls.some(call => call.url === '/audits/filter'), 'invalid date range rejected before API call');
  await setInput(start, '2026-10-01T10:00');
  const ip = document.querySelector('form[aria-label="Audit filters"] input:not([type])');
  await setInput(ip, '198.51.100.9'); button('Apply filters').click();
  await wait(() => fixture.calls.some(call => call.url === '/audits/filter'));
  const filtered = fixture.calls.find(call => call.url === '/audits/filter');
  check(filtered.params.page === 0 && filtered.params.ipAddress === '198.51.100.9', 'applied filters reset pagination and send exact IP');
  check(!('clientId' in filtered.params) && !('eventType' in filtered.params), 'blank optional filters omitted');
  button('Clear filters').click();
  await wait(() => !document.querySelector('form input[type=datetime-local]')?.value);
  check(document.body.textContent.includes('All retained events'), 'clear filters restores unfiltered scope');
  button('Analytics').click();
  await wait(() => document.body.textContent.includes('Successful events'));
  check(document.body.textContent.includes('80%'), 'analytics renders server KPI values');
  fixture.kpiStatus = 500; button('Refresh').click();
  await wait(() => document.querySelector('[role=alert]'));
  check(!document.querySelector('[role=alert]').textContent.includes('private'), 'server failure hides internal details');
  button('Logs').click();
  await wait(() => button('View event'));
  check(!document.querySelector('[role=alert]'), 'KPI failure does not hide working audit list');
  button('Timeline').click();
  await wait(() => document.querySelector('option[value="30d"]'));
  const period = document.querySelector('option[value="30d"]').parentElement;
  period.value = '30d'; period.dispatchEvent(new Event('change', { bubbles: true }));
  await wait(() => fixture.calls.some(call => call.url === '/audits/recent' && call.params.days === 30));
  check(true, 'timeline period calls recent endpoint with chosen days');
  check(document.documentElement.scrollWidth <= innerWidth, 'audit page fits viewport');
  return { passed: results.length, viewport: [innerWidth, innerHeight], results };
})()
